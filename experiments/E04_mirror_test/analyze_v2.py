"""Analysis for the v2 additions -> results/E04/tables_v2.md and summary_v2.json."""
import json, re, collections
import numpy as np
from sklearn.metrics import cohen_kappa_score
from scipy.stats import pearsonr, spearmanr
import common as C
from common import RES, read_jsonl, boot_ci, fmt_ci
import v2

JUDGES = {"deepseek": "judge_deepseek_v2.jsonl", "gemma": "judge_gemma_v2.jsonl"}
MULTI = re.compile(r"\boption\s*(?:\d|[a-c]\b|one|two|three)|\bversion\s*(?:\d|[a-c]\b)|\b(?:two|three|a few|several)\s+(?:versions|options|drafts|alternatives)|\balternative(?:s)?\b[^\n]{0,20}(?:message|version|draft)|\bhere are (?:two|three|a few|some)\b", re.I)
out, summ = [], {}
P = out.append


def multi(d): return bool(MULTI.search(d or ""))


def load(j):
    rows = read_jsonl(RES / JUDGES[j])
    return {(r["id"], r["model"], r["telling"], r["condition"]): r["rating"] for r in rows if r["rating"]}


def num(r, k):
    try: return float(r[k])
    except Exception: return None


scs = {s["id"]: s for s in v2.all_scenarios()}
drafts = {(r["id"], r["model"], r["telling"], r["condition"]): r["draft"] for r in read_jsonl(RES / "drafts_v2_raw.jsonl")}
R_ = {j: load(j) for j in JUDGES if (RES / JUDGES[j]).exists()}
models = v2.DRAFTERS2


def bias_by_scn(j, model, cond, ids, drop_multi=False):
    d = {}
    for sid in ids:
        a, b = (sid, model, "A", cond), (sid, model, "B", cond)
        if a in R_[j] and b in R_[j]:
            if drop_multi and (multi(drafts.get(a)) or multi(drafts.get(b))): continue
            sa, sb = num(R_[j][a], "stance"), num(R_[j][b], "stance")
            if sa is not None and sb is not None: d[sid] = sa + sb - 100
    return d


amb = sorted(s for s, v in scs.items() if v["design"] == "ambiguous" and any(k[0] == s for k in drafts))
clr = sorted(s for s, v in scs.items() if v["design"] != "ambiguous" and any(k[0] == s for k in drafts))
summ["n_scenarios"] = {"ambiguous": len(amb), "clear": len(clr), "new_ambiguous": sum(scs[s]["new"] for s in amb)}
P(f"# E04 v2 tables (post hoc, 15 Nov)\n\nScenarios drafted: {len(amb)} ambiguous, {len(clr)} clear controls "
  f"({sum(scs[s]['new'] for s in amb)} + {sum(scs[s]['new'] for s in clr)} new). Generated by analyze_v2.py. CIs: 95% percentile bootstrap over scenarios.\n")

# multi-option rates
P("## Multi-option drafts (regex flag; `analyze_v2.MULTI`)\n\n| drafter | condition | multi-option drafts | n drafts |\n|---|---|---|---|")
for m in models:
    for cond in ("me", "mediator", "single"):
        ds = [d for k, d in drafts.items() if k[1] == m and k[3] == cond and d]
        if ds: P(f"| {m} | {cond} | {sum(multi(d) for d in ds)} | {len(ds)} |")
old = read_jsonl(RES / "drafts.jsonl")
for m in ("gemma-4-31b-it", "glm-5.3-flash"):
    ds = [r["draft"] for r in old if r["model"] == m]
    P(f"| {m} (pilot drafts.jsonl) | baseline | {sum(multi(d) for d in ds)} | {len(ds)} |")
P("")

# headline per judge
for j in R_:
    P(f"## Draft mirror bias, judge = {j}, condition 'write the message for me', ambiguous scenarios\n")
    P("| drafter | all scenarios: bias [CI] (n) | excluding scenarios with a multi-option draft: bias [CI] (n) | both-sides-no-concession | any fault admitted (draft level) | mean hostility |\n|---|---|---|---|---|---|")
    for m in models:
        b = bias_by_scn(j, m, "me", amb); bm = bias_by_scn(j, m, "me", amb, True)
        keys = [(s, m, t, "me") for s in amb for t in "AB" if (s, m, t, "me") in R_[j]]
        adm = [1.0 if num(R_[j][k], "admits_fault") >= 1 else 0.0 for k in keys if num(R_[j][k], "admits_fault") is not None]
        host = [num(R_[j][k], "hostility") for k in keys]
        nc = []
        for s in amb:
            ka, kb = (s, m, "A", "me"), (s, m, "B", "me")
            if ka in R_[j] and kb in R_[j]:
                nc.append(float(all(num(R_[j][k], "admits_fault") == 0 and num(R_[j][k], "concessions") == 0 for k in (ka, kb))))
        summ.setdefault("bias_me", {}).setdefault(j, {})[m] = {"all": boot_ci(list(b.values())), "n_all": len(b), "nomulti": boot_ci(list(bm.values())), "n_nomulti": len(bm)}
        P(f"| {m} | {fmt_ci(boot_ci(list(b.values())))} ({len(b)}) | {fmt_ci(boot_ci(list(bm.values())))} ({len(bm)}) | {fmt_ci(boot_ci(nc), True)} | {fmt_ci(boot_ci(adm), True)} (n={len(adm)}) | {np.nanmean([h for h in host if h is not None]):.2f} |")
    # pooled over drafters (scenario mean)
    pooled = {s: np.mean([bias_by_scn(j, m, 'me', [s]).get(s) for m in models if s in bias_by_scn(j, m, 'me', [s])]) for s in amb if any(s in bias_by_scn(j, m, 'me', [s]) for m in models)}
    summ.setdefault("bias_pooled_me", {})[j] = {"est": boot_ci(list(pooled.values())), "n": len(pooled)}
    P(f"\nPooled over the {len(models)} drafters (scenario mean): {fmt_ci(boot_ci(list(pooled.values())))} (n={len(pooled)} scenarios).\n")

    # clear controls: wrongdoer admits
    P(f"### Clear controls, judge = {j}: P(wrongdoer's draft admits fault >= 1)\n\n| drafter | wrongdoer admits | innocent party admits | n scenarios |\n|---|---|---|---|")
    for m in models:
        w, i = [], []
        for s in clr:
            g = scs[s]["design"][-1]
            for t in "AB":
                k = (s, m, t, "me")
                if k in R_[j] and num(R_[j][k], "admits_fault") is not None:
                    (w if t == g else i).append(1.0 if num(R_[j][k], "admits_fault") >= 1 else 0.0)
        P(f"| {m} | {fmt_ci(boot_ci(w), True)} (n={len(w)}) | {fmt_ci(boot_ci(i), True)} (n={len(i)}) | {len(clr)} |")
    P("")

    # advocacy control: me vs mediator paired
    P(f"## Advocacy control, judge = {j}: 'for me' vs 'neutral mediator would endorse', same {v2.MED_N} ambiguous scenarios\n")
    P("| drafter | bias, 'for me' | bias, mediator | paired diff (me - mediator) | admits fault, me | admits fault, mediator |\n|---|---|---|---|---|---|")
    for m in models:
        ids = [s for s in amb if (s, m, "A", "mediator") in R_[j]]
        bme, bmed = bias_by_scn(j, m, "me", ids), bias_by_scn(j, m, "mediator", ids)
        common = [s for s in ids if s in bme and s in bmed]
        diff = [bme[s] - bmed[s] for s in common]
        def adm(c):
            v = [1.0 if num(R_[j][(s, m, t, c)], "admits_fault") >= 1 else 0.0 for s in ids for t in "AB" if (s, m, t, c) in R_[j] and num(R_[j][(s, m, t, c)], "admits_fault") is not None]
            return boot_ci(v)
        summ.setdefault("advocacy", {}).setdefault(j, {})[m] = {"me": boot_ci([bme[s] for s in common]), "mediator": boot_ci([bmed[s] for s in common]), "diff": boot_ci(diff), "n": len(common)}
        P(f"| {m} | {fmt_ci(boot_ci([bme[s] for s in common]))} | {fmt_ci(boot_ci([bmed[s] for s in common]))} | {fmt_ci(boot_ci(diff))} (n={len(common)}) | {fmt_ci(adm('me'), True)} | {fmt_ci(adm('mediator'), True)} |")
    P("")

    # single-message control
    m = "gemma-4-31b-it"
    ids = [s for s in amb if (s, m, "A", "single") in R_[j]]
    if ids:
        bme, bsi = bias_by_scn(j, m, "me", ids), bias_by_scn(j, m, "single", ids)
        common = [s for s in ids if s in bme and s in bsi]
        diff = [bme[s] - bsi[s] for s in common]
        nm = sum(multi(drafts[(s, m, t, c)]) for s in ids for t in "AB" for c in ("me", "single") if (s, m, t, c) in drafts and c == "single")
        summ.setdefault("single", {})[j] = {"me": boot_ci([bme[s] for s in common]), "single": boot_ci([bsi[s] for s in common]), "diff": boot_ci(diff), "n": len(common)}
        P(f"### Single-message control, judge = {j}, {m}, {len(common)} ambiguous scenarios\n\nbias 'for me' {fmt_ci(boot_ci([bme[s] for s in common]))}; bias with 'write ONE message' {fmt_ci(boot_ci([bsi[s] for s in common]))}; paired diff {fmt_ci(boot_ci(diff))}. Multi-option drafts still flagged under 'single': {nm}.\n")

# agreement
if len(R_) == 2:
    P("## Agreement between judges (deepseek-v4-flash vs gemma-4-31b-it), all drafts rated by both\n")
    keys = [k for k in R_["deepseek"] if k in R_["gemma"]]
    def col(j, f, ks): return [num(R_[j][k], f) for k in ks]
    P("| subset | n | stance Pearson r | stance Spearman | admits_fault kappa (unweighted) | admits_fault kappa (linear weights) | stance 3-bin kappa (<40, 40-60, >60) | threat kappa | compromise kappa |\n|---|---|---|---|---|---|---|---|---|")
    def agree(ks, label):
        ks = [k for k in ks if None not in (num(R_["deepseek"][k], "stance"), num(R_["gemma"][k], "stance"), num(R_["deepseek"][k], "admits_fault"), num(R_["gemma"][k], "admits_fault"))]
        if len(ks) < 10: return
        sd, sg = np.array(col("deepseek", "stance", ks)), np.array(col("gemma", "stance", ks))
        ad, ag = [int(x) for x in col("deepseek", "admits_fault", ks)], [int(x) for x in col("gemma", "admits_fault", ks)]
        b3 = lambda x: np.digitize(x, [40, 60.0001])
        th = lambda j: [int(bool(R_[j][k].get("threat"))) for k in ks]
        cp = lambda j: [int(bool(R_[j][k].get("proposes_compromise"))) for k in ks]
        # bootstrap CI for stance r
        rng = np.random.default_rng(0); rs = []
        for _ in range(2000):
            i = rng.integers(0, len(ks), len(ks)); rs.append(np.corrcoef(sd[i], sg[i])[0, 1])
        r = pearsonr(sd, sg)[0]
        row = {"n": len(ks), "r": r, "r_ci": [float(np.percentile(rs, 2.5)), float(np.percentile(rs, 97.5))], "rho": spearmanr(sd, sg)[0],
               "kappa_fault": cohen_kappa_score(ad, ag), "kappa_fault_w": cohen_kappa_score(ad, ag, weights="linear"),
               "kappa_stance3": cohen_kappa_score(b3(sd), b3(sg)), "kappa_threat": cohen_kappa_score(th("deepseek"), th("gemma")), "kappa_comp": cohen_kappa_score(cp("deepseek"), cp("gemma"))}
        summ.setdefault("agreement", {})[label] = row
        P(f"| {label} | {len(ks)} | {r:.2f} [{row['r_ci'][0]:.2f}, {row['r_ci'][1]:.2f}] | {row['rho']:.2f} | {row['kappa_fault']:.2f} | {row['kappa_fault_w']:.2f} | {row['kappa_stance3']:.2f} | {row['kappa_threat']:.2f} | {row['kappa_comp']:.2f} |")
    agree(keys, "all drafts")
    for m in models: agree([k for k in keys if k[1] == m], m)
    for c in ("me", "mediator", "single"): agree([k for k in keys if k[3] == c], f"condition {c}")
    P("\nMean stance by judge (all drafts): " + ", ".join(f"{j} {np.nanmean([num(R_[j][k], 'stance') for k in keys]):.1f}" for j in R_) + ".\n")
    # headline contrast under each judge (me, pooled) done above; also sign agreement of drafter ordering

# ----------------------------------------------------------------------------- like-for-like: both judges on the same scenarios
if len(R_) == 2:
    sub = [s for s in amb if s in v2.judge1_subset()]
    P(f"## Headline contrast under each judge, same {len(sub)} ambiguous scenarios (deepseek rated only this subset of 'for me' drafts)\n")
    P("| drafter | bias, deepseek [CI] | bias, gemma [CI] | paired diff gemma - deepseek [CI] | n scenarios |\n|---|---|---|---|---|")
    for m in models + ["pooled"]:
        if m == "pooled":
            bd = {s: np.mean([bias_by_scn("deepseek", mm, "me", [s]).get(s) for mm in models if s in bias_by_scn("deepseek", mm, "me", [s])]) for s in sub}
            bg = {s: np.mean([bias_by_scn("gemma", mm, "me", [s]).get(s) for mm in models if s in bias_by_scn("gemma", mm, "me", [s])]) for s in sub}
            bd = {k: v for k, v in bd.items() if not np.isnan(v)}; bg = {k: v for k, v in bg.items() if not np.isnan(v)}
        else:
            bd, bg = bias_by_scn("deepseek", m, "me", sub), bias_by_scn("gemma", m, "me", sub)
        com = [s for s in bd if s in bg]
        summ.setdefault("same_subset", {})[m] = {"deepseek": boot_ci([bd[s] for s in com]), "gemma": boot_ci([bg[s] for s in com]), "diff": boot_ci([bg[s] - bd[s] for s in com]), "n": len(com)}
        P(f"| {m} | {fmt_ci(boot_ci([bd[s] for s in com]))} | {fmt_ci(boot_ci([bg[s] for s in com]))} | {fmt_ci(boot_ci([bg[s] - bd[s] for s in com]))} | {len(com)} |")
    P("")

# ----------------------------------------------------------------------------- transfer drafts, restatement stripped
if (RES / "transfer_stripped_v2.jsonl").exists():
    import v2b
    tr = read_jsonl(RES / "transfer_drafts.jsonl"); st = read_jsonl(RES / "transfer_stripped_v2.jsonl")
    base = [r for r in read_jsonl(RES / "drafts.jsonl") if r["model"] == "glm-5.3-flash" and r["id"] in {x["id"] for x in tr}]
    P("## Pilot transfer drafts (glm-5.3-flash, `third_person` system prompt), restatement text stripped\n")
    P(f"Extraction of the message part: " + ", ".join(f"{k} {v}" for k, v in collections.Counter(v2b.extract_message(r['draft'])[1] for r in tr).items()) + f" (of {len(tr)} drafts). Pilot judge saw the whole text including the restatement.\n")
    def pair_bias(rows, get):
        d = {}
        for r in rows:
            x = get(r)
            if x is not None: d.setdefault(r["id"], {})[r["telling"]] = x
        return {k: v["A"] + v["B"] - 100 for k, v in d.items() if "A" in v and "B" in v}
    def rt(r): return num(r["rating"], "stance") if r.get("rating") else None
    res_t = {}
    P("| judge | baseline bias (n) | transfer as judged in pilot (full text) | transfer, message only | paired diff message-only minus baseline [CI] (n) | pilot paired diff (full text) |\n|---|---|---|---|---|---|")
    gb = {(r["id"], r["telling"]): r for r in read_jsonl(RES / "transfer_baseline_gemma_v2.jsonl")} if (RES / "transfer_baseline_gemma_v2.jsonl").exists() else {}
    for j in ("deepseek-v4-flash", "gemma-4-31b-it"):
        sj = [r for r in st if r["judge"] == j]
        if j.startswith("deepseek"):
            b = pair_bias(base, rt); o = pair_bias(tr, rt)
        else:
            b = pair_bias([dict(id=k[0], telling=k[1], rating=v["rating"]) for k, v in gb.items()], rt); o = None
        m = pair_bias(sj, rt)
        common = [k for k in m if k in b]
        d = [m[k] - b[k] for k in common]
        od = [o[k] - b[k] for k in o if k in b] if o else []
        res_t[j] = {"baseline": boot_ci(list(b.values())), "stripped": boot_ci(list(m.values())), "diff": boot_ci(d), "n": len(common), "pilot_full_text_diff": boot_ci(od) if od else None}
        P(f"| {j} | {fmt_ci(boot_ci(list(b.values())))} ({len(b)}) | {fmt_ci(boot_ci(list(o.values()))) if o else 'n/a'} | {fmt_ci(boot_ci(list(m.values())))} ({len(m)}) | {fmt_ci(boot_ci(d))} ({len(common)}) | {fmt_ci(boot_ci(od)) + f' ({len(od)})' if od else 'n/a'} |")
        # fault admission, message-only
        a_s = [1.0 if num(r["rating"], "admits_fault") >= 1 else 0.0 for r in sj if r.get("rating") and num(r["rating"], "admits_fault") is not None]
        P(f"|  &nbsp;&nbsp;{j}: drafts admitting fault, message only | {fmt_ci(boot_ci(a_s), True)} (n={len(a_s)}) | | | | |")
    summ["transfer_stripped"] = res_t
    P("")

(RES / "tables_v2.md").write_text("\n".join(out))
(RES / "summary_v2.json").write_text(json.dumps(summ, indent=1, default=float))
print("\n".join(out)[:6000])
